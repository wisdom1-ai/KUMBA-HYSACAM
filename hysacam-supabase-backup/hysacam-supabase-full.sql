-- ===== schema/02_tables.sql =====
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id),
  full_name text NOT NULL DEFAULT '' CHECK (char_length(full_name) <= 120),
  email text CHECK (email IS NULL OR char_length(email) <= 255),
  phone text CHECK (phone IS NULL OR char_length(phone) <= 30),
  role public.user_role NOT NULL DEFAULT 'resident',
  approval_status public.approval_status NOT NULL DEFAULT 'approved',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.dustbins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (char_length(btrim(name)) >= 1 AND char_length(btrim(name)) <= 120),
  latitude double precision CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90)),
  longitude double precision CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
  location_description text CHECK (location_description IS NULL OR char_length(location_description) <= 500),
  created_at timestamptz DEFAULT now(),
  area text CHECK (area IS NULL OR char_length(area) <= 120),
  status public.dustbin_status NOT NULL DEFAULT 'available',
  last_cleaned_at timestamptz,
  assigned_worker_id uuid REFERENCES public.profiles(id),
  updated_at timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.dustbins IS 'Stores register dustbins in kumba.';

CREATE TABLE public.collection_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  dustbin_id bigint REFERENCES public.dustbins(id),
  dustbin_name text,
  dustbin_area text,
  assigned_worker_id uuid REFERENCES public.profiles(id),
  status public.task_status NOT NULL DEFAULT 'pending',
  priority public.task_priority NOT NULL DEFAULT 'medium',
  instructions text CHECK (instructions IS NULL OR char_length(instructions) <= 1000),
  assigned_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  completion_notes text CHECK (completion_notes IS NULL OR char_length(completion_notes) <= 1000),
  created_by uuid REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.cleaning_history (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  dustbin_id bigint REFERENCES public.dustbins(id),
  dustbin_name text,
  dustbin_area text,
  worker_id uuid REFERENCES public.profiles(id),
  task_id uuid REFERENCES public.collection_tasks(id),
  cleaned_at timestamptz NOT NULL DEFAULT now(),
  recorded_status public.dustbin_status NOT NULL DEFAULT 'collected',
  notes text CHECK (notes IS NULL OR char_length(notes) <= 1000),
  valid_until timestamptz NOT NULL,
  idempotency_key text UNIQUE CHECK (idempotency_key IS NULL OR (char_length(idempotency_key) >= 8 AND char_length(idempotency_key) <= 100)),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.community_reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reporter_id uuid REFERENCES public.profiles(id),
  report_type public.report_type NOT NULL,
  description text NOT NULL CHECK (char_length(btrim(description)) >= 5 AND char_length(btrim(description)) <= 2000),
  latitude double precision CHECK (latitude IS NULL OR (latitude >= -90 AND latitude <= 90)),
  longitude double precision CHECK (longitude IS NULL OR (longitude >= -180 AND longitude <= 180)),
  location_description text CHECK (location_description IS NULL OR char_length(location_description) <= 500),
  photo_url text CHECK (photo_url IS NULL OR (photo_url ~ '^https://' AND char_length(photo_url) <= 500)),
  dustbin_id bigint REFERENCES public.dustbins(id),
  status public.report_status NOT NULL DEFAULT 'submitted',
  assigned_worker_id uuid REFERENCES public.profiles(id),
  resolution_notes text CHECK (resolution_notes IS NULL OR char_length(resolution_notes) <= 1000),
  resolved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.report_contacts (
  report_id uuid PRIMARY KEY REFERENCES public.community_reports(id),
  contact_info text NOT NULL CHECK (char_length(btrim(contact_info)) >= 3 AND char_length(btrim(contact_info)) <= 200),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.report_history (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  report_id uuid NOT NULL REFERENCES public.community_reports(id),
  old_status public.report_status,
  new_status public.report_status NOT NULL,
  changed_by uuid REFERENCES public.profiles(id),
  changed_at timestamptz NOT NULL DEFAULT now()
);

